using MevGovernanceBackend.Services;
using MevGovernanceBackend.Controllers;
using MevGovernanceBackend.Data;
using MevGovernanceBackend.Models;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Configuration;
using Microsoft.AspNetCore.Http;
using Microsoft.AspNetCore.Mvc;
using Microsoft.AspNetCore.Mvc.Filters;
using Microsoft.AspNetCore.Mvc.Abstractions;
using Microsoft.AspNetCore.Routing;
using System.Security.Claims;
using System.IdentityModel.Tokens.Jwt;
using System.Reflection;
using System.Text.Json;

int checks = 0;
void Check(bool condition, string name) { if (!condition) throw new Exception(name); checks++; }
var config = new ConfigurationBuilder().AddInMemoryCollection(new Dictionary<string, string?> { ["Jwt:Key"] = new string('x', 64), ["Jwt:Issuer"] = "test", ["Jwt:Audience"] = "test" }).Build();
using var db = new AppDbContext(new DbContextOptionsBuilder<AppDbContext>().UseSqlite("Data Source=:memory:").Options, config);
db.Database.OpenConnection(); db.Database.EnsureCreated();
var user = new AppUser { Username = "operator", Role = "Admin" };
var super = new AppUser { Username = "super", Role = "SuperAdmin" };
var bid = new AppUser { Username = "bid", Role = "Bid Manager" };
db.Users.AddRange(user, super, bid);
var a = new Ambiente { CodiceContratto = "A", IsActive = true };
var b = new Ambiente { CodiceContratto = "B", IsActive = true };
db.Ambienti.AddRange(a, b); db.SaveChanges();
db.UserAmbienti.AddRange(new UserAmbiente { UserId = user.Id, AmbienteId = a.Id, Ruolo = "Editor" }, new UserAmbiente { UserId = user.Id, AmbienteId = b.Id, Ruolo = ContractRoles.Store(new[] { "Developer", "Client" }) }); db.SaveChanges();
Check(ContractRoles.ForUser(db, user, a.Id).SequenceEqual(new[] { "Editor" }), "Account Admin must not override contract Editor");
Check(ContractRoles.ForUser(db, user, b.Id).Order().SequenceEqual(new[] { "Client", "Developer" }), "Multiple roles scoped to B");
Check(ContractRoles.ForUser(db, user, 0).Length == 0, "No contract grants no operational roles");
Check(ContractRoles.ForUser(db, super, 0).Contains("SuperAdmin"), "SuperAdmin needs no membership");
Check(ContractRoles.ForUser(db, bid, 0).Contains("Bid Manager"), "Bid Manager without contract can access tenders");
Check(!ContractRoles.ForUser(db, user, a.Id).Contains("Bid Manager"), "Editor has no tender role");
Check(ContractRoles.Read("Editor").SequenceEqual(new[] { "Editor" }), "Legacy single-role compatible");
Check(ContractRoles.Read("[invalid").Length == 0, "Malformed roles cannot grant access");
Check(!ContractRoles.Allowed.Contains("SuperAdmin"), "SuperAdmin cannot be assigned per contract");
var principal = new ClaimsPrincipal(new ClaimsIdentity(new[] { new Claim(ClaimTypes.NameIdentifier, super.Id.ToString()), new Claim(ClaimTypes.Role, "SuperAdmin") }, "test"));
var controller = new AmbienteController(db) { ControllerContext = new ControllerContext { HttpContext = new DefaultHttpContext { User = principal } } };
Check(controller.UpdateUtenteRuolo(a.Id, user.Id, new UpdateRuoloRequest(Ruoli: new[] { "Editor", "Developer" })) is OkObjectResult, "Update multiple roles accepted");
Check(ContractRoles.ForUser(db, user, a.Id).Order().SequenceEqual(new[] { "Developer", "Editor" }), "Both roles persisted");
Check(controller.UpdateUtenteRuolo(a.Id, user.Id, new UpdateRuoloRequest(Ruoli: Array.Empty<string>())) is BadRequestObjectResult, "Empty set rejected");
Check(controller.UpdateUtenteRuolo(a.Id, user.Id, new UpdateRuoloRequest(Ruoli: new[] { "SuperAdmin" })) is BadRequestObjectResult, "Per-contract elevation to SuperAdmin rejected");
Check(controller.AddUtente(a.Id, new UserAmbienteRequest(super.Id, Ruoli: new[] { "Admin" })) is BadRequestObjectResult, "SuperAdmin not associated");
var payload = JsonSerializer.Serialize(((OkObjectResult)controller.GetUtenti(a.Id)).Value);
Check(payload.Contains("Developer") && payload.Contains("Editor"), "Membership response includes all roles");
var auth = new AuthController(db, config);
var tokenMethod = typeof(AuthController).GetMethod("GenerateToken", BindingFlags.NonPublic | BindingFlags.Instance)!;
var encoded = (string)tokenMethod.Invoke(auth, new object?[] { user, a.Id, null })!;
var jwt = new JwtSecurityTokenHandler().ReadJwtToken(encoded);
var tokenRoles = jwt.Claims.Where(c => c.Type == ClaimTypes.Role || c.Type == "role").Select(c => c.Value).ToArray();
Check(tokenRoles.Contains("Editor") && tokenRoles.Contains("Developer") && !tokenRoles.Contains("Admin"), "JWT uses selected contract roles");
b.IsActive = false; db.SaveChanges();
Check(ContractRoles.ForUser(db, user, b.Id).Length == 0, "Inactive contract grants no roles");
var dummyController = new TestContractController();
var context = new ActionExecutingContext(new ActionContext(new DefaultHttpContext { User = new ClaimsPrincipal(new ClaimsIdentity(new[] { new Claim(ClaimTypes.NameIdentifier, user.Id.ToString()), new Claim("ambienteId", "0") }, "test")) }, new RouteData(), new ActionDescriptor()), new List<IFilterMetadata>(), new Dictionary<string, object?>(), dummyController);
new ContractAccessFilter(db).OnActionExecuting(context);
Check(context.Result is ForbidResult, "Contract endpoints forbid missing scope");
var gara = new GareController(null!, db, config) { ControllerContext = new ControllerContext { HttpContext = new DefaultHttpContext { User = new ClaimsPrincipal(new ClaimsIdentity(new[] { new Claim(ClaimTypes.Role, "Admin") }, "test")) } } };
var canAccess = typeof(GareController).GetMethod("CanAccess", BindingFlags.NonPublic | BindingFlags.Instance)!;
Check(!(bool)canAccess.Invoke(gara, null)!, "Admin cannot access tender APIs");
gara.HttpContext.User = new ClaimsPrincipal(new ClaimsIdentity(new[] { new Claim(ClaimTypes.Role, "Bid Manager") }, "test"));
Check((bool)canAccess.Invoke(gara, null)!, "Bid Manager can access tender APIs without contract");
Console.WriteLine($"PASS: {checks} authorization checks");
class TestContractController : BaseController { }
